def fetch_api_data(api_base, auth_token, proxy_url=None, game_ver="1.2.0", sdk_ver="1.19.20.0", app_ver="1.0.2.0"):
    proxies = {"http": proxy_url, "https": proxy_url} if proxy_url and proxy_url.strip() else None
        
    print("[1/3] Fetching master data table (GameDataTable)...")
    headers1 = make_headers(auth_token, game_ver, sdk_ver, app_ver)
    res_table = requests.post(f"{api_base}/GameDataTable/FetchDataTable", headers=headers1, json={}, proxies=proxies, verify=False, timeout=15)
    if res_table.status_code != 200:
        raise Exception(f"Failed to fetch DataTable: {res_table.status_code} {res_table.text}")
    
    table_data = res_table.json()
    
    time.sleep(0.5)
    print("[2/3] Fetching player cloud save (GameSave)...")
    headers2 = make_headers(auth_token, game_ver, sdk_ver, app_ver)
    res_save = requests.post(f"{api_base}/GameSave/Fetch", headers=headers2, json={}, proxies=proxies, verify=False, timeout=15)
    if res_save.status_code != 200:
        raise Exception(f"Failed to fetch GameSave: {res_save.status_code} {res_save.text}")
    
    save_data = res_save.json()
    return table_data, save_data

